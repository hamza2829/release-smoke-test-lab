import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "../envs/release.js";
import { TICKETS } from "./catalog.js";
import { REPRO_VERSION, runTicket, withBrowser } from "./harness.js";

export function fillTemplate(template: string, values: Record<string, string>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
    if (!(key in values)) throw new Error(`Template value missing: ${key}`);
    return values[key];
  });
}

const outDir = process.env.TICKETS_OUT ?? join(ROOT, "tickets", "reports");
mkdirSync(join(outDir, "screenshots"), { recursive: true });
const template = readFileSync(join(ROOT, "tickets", "TEMPLATE.md"), "utf8");
const date = new Date().toISOString().slice(0, 10);

const rows: string[] = [];
let reproduced = 0;
await withBrowser(async (browser) => {
  for (const t of TICKETS) {
    const obs = await runTicket(browser, t, true, join(outDir, "screenshots", `${t.id}.png`));
    if (obs.failed) reproduced++;
    const md = fillTemplate(template, {
      id: t.id,
      title: t.title,
      severity: t.severity,
      area: t.area,
      date,
      environment: `LernWerk ${REPRO_VERSION}, local instance with seeded fault \`${t.fault}\`, Chromium (Playwright) 1000x640`,
      steps: t.steps.map((s, i) => `${i + 1}. ${s}`).join("\n"),
      expected: t.expected,
      actual: obs.failed ? obs.actual : `Not reproduced (${obs.actual})`,
      notes: `Generated by \`npm run tickets\` from seeded fault \`${t.fault}\`. Reproduction took ${obs.ms} ms. Re-tested by \`npm run verify\`.`,
    });
    writeFileSync(join(outDir, `${t.id}.md`), md);
    rows.push(`| [${t.id}](${t.id}.md) | ${t.title} | ${t.severity} | ${t.area} | ${obs.failed ? "reproduced" : "NOT reproduced"} |`);
    console.log(`${t.id} ${obs.failed ? "reproduced" : "NOT reproduced"} (${obs.ms} ms): ${obs.actual}`);
  }
});
writeFileSync(join(outDir, "README.md"), [
  "# Sample bug reports",
  "",
  "Generated from seeded faults (see `src/faults.ts`) with Playwright screenshots.",
  "",
  "| Ticket | Title | Severity | Area | Reproduction |",
  "|---|---|---|---|---|",
  ...rows,
  "",
].join("\n"));
console.log(`${reproduced}/${TICKETS.length} tickets reproduced`);
process.exit(reproduced === TICKETS.length ? 0 : 1);
